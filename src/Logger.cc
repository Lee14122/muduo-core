/* ============================================================================
 * 【文件】src/Logger.cc
 * 【一句话】实现 Logger 单例：取出唯一实例、记住一个级别整数、把"[级别]时间 : 消息"打到标准输出。
 * 【Reactor 角色】基础设施 —— 全库唯一真正把字节写到屏幕上的地方（std::cout）。
 * 【依赖】<iostream>（std::cout）；"Logger.h"（本文件要实现它声明的类）；
 *         "Timestamp.h"（日志行的时间字段用 Timestamp::now().toString()）。
 * 【谁用它】所有 #include "Logger.h" 并写了 LOG_XXX(...) 的 .cc：
 *           src/Socket.cc、src/Acceptor.cc、src/EPollPoller.cc、src/Channel.cc、src/EventLoop.cc、
 *           src/TcpServer.cc、src/TcpConnection.cc、src/EventLoopThreadPool.cc、example/testserver.cc。
 *           调用它们的不是自己写的语句，而是 include/Logger.h 里那 4 个宏（宏 → instance → setLogLevel → log）。
 * 【关于"原版"】本环境不能联网（github/raw 域名均不可达），仓库里也没有原版副本，
 *             所以下文所有【对比原版】条目都写成"通行描述"，只用来对照设计思路，
 *             接口名与写法一律以原版仓库为准；凡是标了"实测 / grep / man"的结论，才是本机可复现的事实。
 * 【先修知识】1) 函数内 static 变量的存储期与初始化时机；
 *             2) std::cout 与 operator<< 链、std::endl 与 '\n' 的区别；
 *             3) 值传参与 const 引用传参的成本差；
 *             4) 本项目没有任何线程同步原语（无 mutex/atomic）这一事实。
 * 【难度】★★☆☆☆   【建议耗时】25 分钟
 * 【自检】1) 两个线程同时第一次调用 instance()，Logger 会被构造几遍？语言标准靠什么保证？
 *         2) 一条日志发生几次堆分配？分别是哪一步？
 *         3) 把 std::endl 换成 '\n' 输出会有什么行为差别？高并发下哪个更快，为什么？
 *         4) 为什么"级别"能污染到别的线程的日志行？（答：setLogLevel 与 log 是两步，中间没有锁）
 * ========================================================================== */
#include <iostream>

#include "Logger.h"
#include "Timestamp.h"

// 【设计】日志行的格式在这一点统一：[级别] + 时间 + " : " + 消息，
//         实测输出形如 [INFO]2026/11/11 18:20:06 : hello world
//         —— 注意 [INFO] 与时间之间没有空格，时间与 " : " 之间有一个空格。
//         固定前缀让 grep 很好用（grep '^\[ERROR\]' 筛错误日志），
//         【易错】但级别与时间粘连意味着不能靠"列对齐"写脚本解析日志（原版的行格式不同，以原版源码为准）。
// 获取日志唯一的实例对象 单例
Logger &Logger::instance()
{
    // 【语法】函数内的 static 变量（也叫"局部静态"）是单例的地道写法，名叫 Meyers' Singleton：
    //         ① 存储期是整个程序（不在栈上，函数返回后仍在）；
    //         ② 初始化时机是"第一次执行到这一行"（懒加载），不是程序启动时；
    //            也就是说 mainLoop 还没跑之前它不存在，第一次打日志（可能在 ② TcpServer 构造里）才构造；
    //         ③ 【系统调用/语言保证】C++11 [stmt.dcl] 规定：并发执行到这一行时，初始化只发生一次，
    //            后到的线程必须阻塞到初始化完成 —— 编译器为它生成一个 guard 变量和
    //            __cxa_guard_acquire / __cxa_guard_release 调用（内部用 futex 等待）。
    //            这就是 C++11 之后不需要双重检查锁（DCLP）的原因；C++03 时代这段代码是有竞态的，
    //            得自己写 pthread_once 或加锁。
    //         ④ 析构在程序终止（exit / main return）时按"构造完成顺序的逆序"执行。
    //            Logger 没有自定义析构函数、成员只有一个 int，所以这一步实际什么都不做；
    //            【易错】不要指望"程序退出时自动把日志缓冲刷干净"，本项目根本没有缓冲（下一条就是 endl 直接 flush）。
    // 【⚠问题】"初始化线程安全"不等于"用这个对象线程安全"：
    //         guard 只管这一次构造，之后 logLevel_ 的读写仍然没有任何保护（见下面两个函数）。
    // 【对比原版】通行描述（细节以原版仓库为准）：原版不用常驻单例 —— 每条日志在调用点
    //         构造一个栈上临时 Logger（携带级别与 __FILE__/__LINE__/函数名），析构时把整行交给输出函数；
    //         级别跟着对象走，于是没有"共享的可变状态"；此外原版另有级别阈值、可替换输出后端
    //         与异步落盘一整套机制，本库这些都没有。
    // 【线程】谁第一次调它谁构造；之后所有线程共用这一个 logger 对象。
    //         每次调用还要读一次 guard 标志（已初始化后只是一次普通静态变量读，成本很低但非零），
    //         在高频日志路径上，这正是"栈上临时对象"比"全局单例 + 两步调用"更被青睐的原因之一。
    static Logger logger;
    return logger;
}

// 【设计】整个函数只有一次赋值：把宏传进来的级别记到共享成员里。
//         它在每条日志前都会被调用一次（宏体的第二步），也就是 logLevel_ 这个 int
//         会被"每条日志写一次、每条日志读一次"，跨线程共享。
// 【⚠问题】setLogLevel 与 log 是**分开的两步**，中间没有加锁、没有原子操作，也没有把级别作为
//         log 的参数传下去，于是有真实的竞态：
//             线程 A：setLogLevel(INFO)  →  [被抢占]  →  log("A 的内容")
//             线程 B：            setLogLevel(ERROR) → log("B 的内容")
//             A 看到的那一行可能打出 [ERROR]，B 的行也可能拿到 INFO —— 前缀与内容错配。
//         【线程】这在生产环境一定会发生：mainLoop 与每个 subLoop#N 都在打日志
//         （④ 每轮 poll 有 2~3 条 LOG_INFO，⑤⑥⑦⑧⑨⑩⑪ 都有），N 个线程并发写同一个 int，
//         按 C++ 内存模型这是未定义行为（data race），最坏情况编译器可以把这次写优化到循环外。
//         【流程】本文件里的三个函数都覆盖 ①→⑫ 全过程，任何一步的日志都走这条链。
//         修法（本文件不改，留给你动手）：① 把级别当 log(msg, level) 的参数传（消灭共享状态）；
//         ② 或给"设级别 + 输出"这一对操作套一个 static std::mutex；
//         ③ 或改成原版那种"级别跟着栈对象走"的 RAII 日志思路（以原版源码为准）。
// 设置日志级别
void Logger::setLogLevel(int level)
{
    logLevel_ = level;
}

// 【一句话】全库唯一的输出点：把级别换成前缀字符串，然后一次打完。
// 【⚠问题】形参 std::string msg 按值传递（规范点名的退化）：
//         从宏里进来时是 char buf[1024] → 先构造一个临时 std::string（strlen + malloc + memcpy），
//         再拿它移动构造这个形参（右值 → 走移动构造，所以短消息不再多分配一次；
//         如果哪天调用方传的是左值 std::string，就变成一次完整的深拷贝）。
//         实测：一条短日志 2 次堆分配（时间戳串 + 前缀与时间拼接），长消息（>15 字节）3 次。
//         通行描述：原版是在栈上的固定小缓冲区里攒字节，一条日志几乎不分配内存（缓冲区名以原版源码为准）。
//         【易错】按值传参让函数内可以随便改 msg 而不影响调用方，跨线程搬动也不会悬垂
//         （这与 TcpConnection::send 跨线程时用 std::bind 按值拷贝字符串是同一个道理），
//         但本函数只是就地打印，这份"安全"没有任何收益。
//         【设计】另外注意：这里没有级别过滤，无论 logLevel_ 是什么，内容都会打印（见 include/Logger.h 的 logLevel_）。
//         【流程/线程】被 4 个 LOG_XXX 宏调用，覆盖 ①→⑫ 每一步；
//         【线程】既可能在 mainLoop（② bind/listen、⑥ newConnection、⑪ removeConnectionInLoop），
//         也可能在 subLoop#N（④⑤⑦⑧⑨⑩ 的 poll/accept/读写），还可能在用户自己的线程里（如果回调里打了日志）。
//         函数体内没有任何锁，这是本框架日志最需要警惕的地方。
// 写日志 [级别信息] time : msg
void Logger::log(std::string msg)
{
    std::string pre = "";
    // 【设计】先把 pre 置成空串、在 switch 里只改字符串、最后只留一条 cout 语句：
    //         好处是"决定前缀"和"输出"分离，将来要加文件名/线程 id/写文件，只改这一处出口；
    //         代价是每条日志都要走一遍 switch 再拼一次字符串（见下面输出语句的分配分析）。
    //         【语法】std::string 有短字符串优化（SSO）：libstdc++ 下长度 ≤ 15 字节时数据放在对象自身的栈缓冲区，
    //         不 malloc，所以 "[INFO]" 这种前缀本身不分配（实测的 2~3 次分配都花在时间戳和拼接结果上）。
    switch (logLevel_)
    {
        // 【语法】switch 的分支变量必须是整型；enum → int 的隐式转换让这里的 case 标签能用。
        //         case 标签是编译期常量，不能写成 case logLevel_: 。
    case INFO:
        pre = "[INFO]";
        break;
    case ERROR:
        pre = "[ERROR]";
        break;
    case FATAL:
        pre = "[FATAL]";
        break;
        // 【流程】这个分支在默认编译配置下永远走不到：include/Logger.h 里的 LOG_DEBUG 宏在没有
        //         MUDEBUG 时展开为空，根本不会调用 log()，也就没人把 logLevel_ 设成 DEBUG(3)。
        //         【易错】只有手动写 logger.setLogLevel(DEBUG) 才可能走到这里 ——
        //         读日志代码时要把"宏的编译期开关"和"这个 switch 的运行期分支"两层结合起来看，
        //         否则会误以为"把级别设成 DEBUG 就能看调试日志"（实际上调试日志的调用点在编译期就没了）。
    case DEBUG:
        pre = "[DEBUG]";
        break;
    default:
        break;
        // 【易错】default 什么都不做，pre 保持空串：级别非法（setLogLevel(99)、
        //         或者上面提到的"栈上 Logger 对象的 logLevel_ 是随机值"）时，
        //         日志仍然会打印，只是行首没有 [XXX]，肉眼很难发现"这条日志的级别丢了"。
        //         更稳的写法是 default: pre = "[UNKNOWN]"，或直接拒绝输出；本项目没做（不改代码）。
    }

    // 【语法】这一行是 4 次 operator<< 的链式调用，等价于 (((cout << A) << " : ") << msg) << endl;
    //         每个 << 返回 cout 的引用，所以能一直串下去 —— 这也是 std::endl 放在最后的后果
    //         （它 flush 的是整行写完之后的流）。
    //         注意 std::string 的 + 要求至少一边是 std::string：这里 pre + toString() 两个都是 string，合法；
    //         但 "x" + "y" 这种两个字符串字面量相加是"指针相加"，编译不过（字面量之间要相邻拼接只能靠
    //         "abc" "def" 这种没有加号的写法）。
    //         【易错】表达式里一共隐含 3 个临时 std::string（前缀、时间戳、拼接结果），
    //         拼接结果比 pre 长（6+19=25 字节，超过 SSO 的 15 字节上限）所以必然堆分配。
    //         更省的做法是把前缀 << 进流，或用一条 snprintf 生成整行再输出。
    // 【⚠问题】时间只到秒：Timestamp::now() 塞的是秒、这里当秒格式化（见 src/Timestamp.cc 的 now/toString），
    //         所以高并发下大量日志共享同一个时间戳，无法按时间排序、无法测耗时，
    //         排障时"哪条在前"只能靠输出顺序猜（通行描述：原版的时间精度更高，具体位数以原版源码为准）。
    // 【系统调用】std::endl 做两件事：写入 '\n' 并 flush()。
    //         flush 在 stdout 上是"把 iostream 缓冲里的字节交给 C 层，最终走到 write(2) 系统调用"。
    //         是否真的立刻陷内核取决于目的地：终端（isatty 为真）默认行缓冲，本来每行就刷；
    //         重定向到文件/管道则是全缓冲，endl 强制提前 write，
    //         实测本函数每条日志都会产生一次写系统调用。
    //         【易错】把 endl 换成 '\n' 的话，程序崩溃时最后几百行日志可能整块还堵在缓冲里（看不见），
    //         所以"改成 '\n' 提速"和"崩溃时丢日志"是一对必须自己权衡的取舍；
    //         本项目里 LOG_FATAL 那条日志能打出来，靠的就是这里的 endl
    //         （另见 include/Logger.h 中 LOG_FATAL 宏注释里关于 exit() 与缓冲刷新的实测结论）。
    //         【对比原版】通行描述：原版每条日志只写 '\n' 不逐条 flush，高并发场景另有
    //         双缓冲 + 条件变量 + 独立日志线程的异步落盘机制，把写系统调用从"每条一次"摊成"每块一次"
    //         （机制名与默认行为以原版仓库为准）。
    // 【⚠问题】没有锁、没有级别过滤：logLevel_ 的读写是跨线程 data race（未定义行为），
    //         而"一次 << 一行日志"其实是 4 次独立的流插入，标准只保证不同线程对同一个流的
    //         每次插入不会互相踩坏内存，不保证一整行连续输出，
    //         所以两条日志的片段可能交错（表现为一行被"缝合"）。通行描述：原版是先把整行拼进一块缓冲、
    //         再一次交给输出函数，用"一次写出"换来整行不被打断（以原版源码为准）。
    //         【对比原版】通行描述：原版的日志行里带线程 id/线程名（本仓库 src/CurrentThread.cc 只缓存了 tid，
    //         而 Logger 从没把它打进输出）—— 本项目只打时间，多线程日志分不清是谁打的，
    //         这是本框架排障能力最明显的短板（原版行格式以原版仓库为准）。
    // 打印时间和msg
    std::cout << pre + Timestamp::now().toString() << " : " << msg << std::endl;
}